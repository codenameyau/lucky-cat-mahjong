/* Builds the static per-tile pages for the "Which Mahjong Tile Are You?" quiz.
 *
 * Link previews (iMessage, Instagram, etc.) read <meta> tags from the HTML and ignore query strings,
 * so each tile gets its own copy of the quiz page at /which-mahjong-tiles-are-you/<tile-id>/ whose
 * preview tags point at that tile's image. The quiz page itself keeps the Lucky Cat logo.
 */

'use strict';

const SITE_ORIGIN = 'https://luckycatmahjong.com';
const QUIZ_PATH = '/which-mahjong-tiles-are-you/';
const IMAGE_DIR = 'images';
const IMAGE_WIDTH = 1200;
const IMAGE_HEIGHT = 630;
const GENERATED_NOTE = '<!-- Generated by scripts/generate-tile-pages.js from which-mahjong-tiles-are-you/index.html. Edit that file and run `npm run generate-tile-pages`. -->';

function escapeAttr(str) {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function tilePageUrl(tile) {
  return SITE_ORIGIN + QUIZ_PATH + tile.id + '/';
}

function tileImagePath(tile) {
  return QUIZ_PATH + IMAGE_DIR + '/' + tile.id + '.png';
}

function replaceOnce(html, pattern, replacement, label) {
  if (!pattern.test(html)) throw new Error('Quiz page template is missing ' + label);
  return html.replace(pattern, replacement);
}

function setMeta(html, attr, name, value) {
  const pattern = new RegExp('(<meta ' + attr + '="' + name.replace(/:/g, '\\:') + '" content=")[^"]*(">)');
  return replaceOnce(html, pattern, '$1' + escapeAttr(value).replace(/\$/g, '$$$$') + '$2', name);
}

function buildTilePage(template, tile) {
  const url = tilePageUrl(tile);
  const image = SITE_ORIGIN + tileImagePath(tile);
  const title = tile.name + ': ' + tile.title;
  const description = tile.tagline + ' Which mahjong tile are you? Take the quiz.';
  const alt = tile.name + ' chibi mahjong tile, ' + tile.title;

  let html = template.replace(/^<!DOCTYPE html>\n/i, '<!DOCTYPE html>\n' + GENERATED_NOTE + '\n');
  html = replaceOnce(html, /<title>[^<]*<\/title>/, '<title>' + escapeAttr(title) + ' | Which Mahjong Tile Are You?</title>', 'title');
  html = setMeta(html, 'name', 'description', description);
  html = setMeta(html, 'name', 'robots', 'noindex, follow, max-image-preview:large');
  html = replaceOnce(html, /(<link rel="canonical" href=")[^"]*(">)/, '$1' + url + '$2', 'canonical');
  html = setMeta(html, 'property', 'og:title', title);
  html = setMeta(html, 'property', 'og:description', description);
  html = setMeta(html, 'property', 'og:url', url);
  html = setMeta(html, 'property', 'og:image', image);
  html = setMeta(html, 'property', 'og:image:alt', alt);
  html = replaceOnce(html, /(<meta property="og:image:alt" content="[^"]*">)/,
    '$1\n  <meta property="og:image:width" content="' + IMAGE_WIDTH + '">' +
    '\n  <meta property="og:image:height" content="' + IMAGE_HEIGHT + '">', 'og:image:alt');
  html = setMeta(html, 'name', 'twitter:title', title);
  html = setMeta(html, 'name', 'twitter:description', description);
  html = setMeta(html, 'name', 'twitter:image', image);
  html = setMeta(html, 'name', 'twitter:image:alt', alt);
  return html;
}

module.exports = {
  QUIZ_PATH,
  IMAGE_DIR,
  IMAGE_WIDTH,
  IMAGE_HEIGHT,
  buildTilePage,
  tilePageUrl,
  tileImagePath,
};
