/* Builds the per-tile link-preview pages for the "Which Mahjong Tile Are You?" quiz.
 *
 * Link previews (iMessage, Instagram, etc.) read <meta> tags from the HTML and ignore query strings,
 * so each tile gets a small page at /which-mahjong-tiles-are-you/<tile-id>/ that carries that tile's
 * preview tags and immediately redirects to the quiz (?tile=<tile-id>). The quiz then puts the
 * tile page's URL back in the address bar, so sharing from the browser also gets the tile preview.
 */

'use strict';

const SITE_ORIGIN = 'https://luckycatmahjong.com';
const QUIZ_PATH = '/which-mahjong-tiles-are-you/';
const IMAGE_DIR = 'images';
const IMAGE_WIDTH = 1200;
const IMAGE_HEIGHT = 630;

function escapeHtml(str) {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function tilePageUrl(tile) {
  return SITE_ORIGIN + QUIZ_PATH + tile.id + '/';
}

function tileImagePath(tile) {
  return QUIZ_PATH + IMAGE_DIR + '/' + tile.id + '.png';
}

function quizTileUrl(tile) {
  return QUIZ_PATH + '?tile=' + encodeURIComponent(tile.id);
}

function buildTilePage(tile) {
  const url = tilePageUrl(tile);
  const image = SITE_ORIGIN + tileImagePath(tile);
  const target = quizTileUrl(tile);
  const title = escapeHtml(tile.name + ': ' + tile.title);
  const description = escapeHtml(tile.tagline + ' Which mahjong tile are you? Take the quiz.');
  const alt = escapeHtml(tile.name + ' chibi mahjong tile, ' + tile.title);

  return `<!DOCTYPE html>
<!-- Generated by scripts/generate-tile-pages.js. Run \`npm run generate-tile-pages\` after changing a tile's name, title, tagline or art. -->
<html lang="en-US">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${title} | Which Mahjong Tile Are You?</title>
  <meta name="description" content="${description}">
  <meta name="robots" content="noindex, follow">
  <link rel="canonical" href="${url}">

  <meta property="og:type" content="website">
  <meta property="og:site_name" content="Lucky Cat Mahjong">
  <meta property="og:title" content="${title}">
  <meta property="og:description" content="${description}">
  <meta property="og:url" content="${url}">
  <meta property="og:locale" content="en_US">
  <meta property="og:image" content="${image}">
  <meta property="og:image:alt" content="${alt}">
  <meta property="og:image:width" content="${IMAGE_WIDTH}">
  <meta property="og:image:height" content="${IMAGE_HEIGHT}">

  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${title}">
  <meta name="twitter:description" content="${description}">
  <meta name="twitter:image" content="${image}">
  <meta name="twitter:image:alt" content="${alt}">

  <link rel="icon" href="/favicon-32.png" type="image/png" sizes="32x32">
  <meta http-equiv="refresh" content="0; url=${target}">
  <script>location.replace('${target}');</script>
</head>
<body>
  <p><a href="${target}">See the ${escapeHtml(tile.name)}</a></p>
</body>
</html>
`;
}

module.exports = {
  QUIZ_PATH,
  IMAGE_DIR,
  IMAGE_WIDTH,
  IMAGE_HEIGHT,
  buildTilePage,
  tilePageUrl,
  tileImagePath,
  quizTileUrl,
};
