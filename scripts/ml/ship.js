#!/usr/bin/env node
/* Ships a trained model to the page: writes its weights file from
   ml/models/<name>.json (what ml/train.py --ship does for Neural Cat).

   node scripts/ml/ship.js ml/models/s3.json              (js/mahjong-ml-weights.js)
   node scripts/ml/ship.js ml/models/l3.json lucky-cat    (js/mahjong-lucky-cat-weights.js)
   node scripts/ml/ship.js ml/models/O2.json only-orphans (js/mahjong-only-orphans-weights.js)

   Neural Cat's shipped models get a release name, NC1, NC2 and so on, which
   the game shows (easier to read than the league's L17). Lucky Cat's go on
   from its league's: lc20, then lc21 for the lab's first champion (LL1a).
   Each model that ships gets the next number, counted from the weights
   already shipped; shipping the same model again keeps its name. The
   training name stays in meta.trainedName, and ml/models/ keeps the file
   under it. */

'use strict';

const fs = require('node:fs');
const path = require('node:path');
const M = require('../../js/mahjong-ml-model.js');
const LN = require('../../js/mahjong-lucky-cat-net.js');

const TARGETS = {
  'neural-cat': { file: 'mahjong-ml-weights.js', global: 'MahjongMLWeights', name: "Neural Cat's", model: M, by: 'scripts/ml/ship.js', release: 'NC' },
  'only-orphans': { file: 'mahjong-only-orphans-weights.js', global: 'MahjongOnlyOrphansWeights', name: "Only Orphans'", model: M, by: 'scripts/ml/ship.js' },
  'lucky-cat': { file: 'mahjong-lucky-cat-weights.js', global: 'MahjongLuckyCatWeights', name: "Lucky Cat's", model: LN, by: 'scripts/ml/ship.js', release: 'lc' },
};

// The release name for meta (e.g. NC2), from the weights shipped in `out`.
function release(m, out, prefix) {
  const trained = m.trainedName || m.name;
  let now = null;
  try { delete require.cache[require.resolve(out)]; now = require(out).meta || null; } catch (err) { now = null; }
  const n = now && new RegExp('^' + prefix + '(\\d+)$').exec(now.name || '');
  m.trainedName = trained;
  m.name = n && now.trainedName === trained ? now.name : prefix + (n ? parseInt(n[1], 10) + 1 : 1);
}

function ship(file, target) {
  const t = TARGETS[target || 'neural-cat'];
  if (!t) throw new Error('ship target is ' + Object.keys(TARGETS).join(' or '));
  const weights = JSON.parse(fs.readFileSync(file, 'utf8'));
  t.model.createModel(weights); // refuses weights for other features
  // An oracle model (Suphx's oracle guiding) reads the hidden tiles: training only.
  // A stacked model's move network reads the features and its reader's read (js/mahjong-ml-model.js).
  const cols = weights.featureSize + (weights.reader ? M.READ_SIZE : 0);
  if ((weights.meta || {}).oracle || weights.layers[0].cols !== cols) {
    throw new Error(file + ' reads hidden tiles (an oracle model): train it on to delta 0 and write it with --public before shipping');
  }
  const m = weights.meta = weights.meta || {};
  const out = path.join(__dirname, '..', '..', 'js', t.file);
  if (t.release) release(m, out, t.release);
  fs.writeFileSync(out,
    '/* ' + t.name + ' trained weights. Generated by ' + t.by + ': do not edit.\n' +
    '   Model ' + m.name + (m.trainedName && m.trainedName !== m.name ? ' (' + m.trainedName + ')' : '') + ', trained ' + m.trainedAt + ' on ' + m.samples + ' samples. */\n' +
    '(function (root) {\n  var W = ' + JSON.stringify(weights) + ';\n' +
    "  if (typeof module !== 'undefined' && module.exports) module.exports = W;\n" +
    '  else root.' + t.global + ' = W;\n' +
    "})(typeof globalThis !== 'undefined' ? globalThis : this);\n");
  return out;
}

if (require.main === module) {
  // The target is the second argument (lucky-cat, only-orphans), or --strategy NAME.
  const k = process.argv.indexOf('--strategy');
  const out = ship(path.resolve(process.argv[2]), k === -1 ? process.argv[3] : process.argv[k + 1]);
  console.log('Shipped ' + out);
}
module.exports = { ship };
