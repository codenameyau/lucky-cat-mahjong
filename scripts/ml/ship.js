#!/usr/bin/env node
/* Ships a trained model to the page: writes js/mahjong-ml-weights.js from
   ml/models/<name>.json (what ml/train.py --ship does), or, with
   --strategy only-orphans, js/mahjong-only-orphans-weights.js.

   node scripts/ml/ship.js ml/models/s3.json
   node scripts/ml/ship.js ml/models/O3.json --strategy only-orphans */

'use strict';

const fs = require('node:fs');
const path = require('node:path');
const M = require('../../js/mahjong-ml-model.js');

const TARGETS = {
  'neural-cat': { file: 'mahjong-ml-weights.js', global: 'MahjongMLWeights', title: "Neural Cat's" },
  'only-orphans': { file: 'mahjong-only-orphans-weights.js', global: 'MahjongOnlyOrphansWeights', title: "Only Orphans'" },
};

function ship(file, strategy) {
  const t = TARGETS[strategy || 'neural-cat'];
  if (!t) throw new Error('unknown strategy ' + strategy + ' (have: ' + Object.keys(TARGETS).join(', ') + ')');
  const weights = JSON.parse(fs.readFileSync(file, 'utf8'));
  M.createModel(weights); // refuses weights for other features
  const m = weights.meta || {};
  const out = path.join(__dirname, '..', '..', 'js', t.file);
  fs.writeFileSync(out,
    '/* ' + t.title + ' trained weights. Generated by scripts/ml/ship.js: do not edit.\n' +
    '   Model ' + m.name + ', trained ' + m.trainedAt + ' on ' + m.samples + ' samples. */\n' +
    '(function (root) {\n  var W = ' + JSON.stringify(weights) + ';\n' +
    "  if (typeof module !== 'undefined' && module.exports) module.exports = W;\n" +
    '  else root.' + t.global + ' = W;\n' +
    "})(typeof globalThis !== 'undefined' ? globalThis : this);\n");
  return out;
}

if (require.main === module) {
  const k = process.argv.indexOf('--strategy');
  const out = ship(path.resolve(process.argv[2]), k === -1 ? 'neural-cat' : process.argv[k + 1]);
  console.log('Shipped ' + out);
}
module.exports = { ship };
